  try {
    const saved = localStorage.getItem('epu.lang');
    if (saved && DICTS[saved]) lang = saved;
  } catch (e) { /* приватный режим */ }

  function t(key, params) {
    const dict = DICTS[lang] || RU;
    let s = dict[key] != null ? dict[key] : (RU[key] != null ? RU[key] : key);
    if (params) {
      for (const k of Object.keys(params)) s = s.split('{' + k + '}').join(params[k]);
    }
    return s;
  }

  function apply(root) {
    const scope = root || document;
    scope.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.getAttribute('data-i18n')); });
    scope.querySelectorAll('[data-i18n-ph]').forEach(el => { el.placeholder = t(el.getAttribute('data-i18n-ph')); });
    scope.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = t(el.getAttribute('data-i18n-title')); });
    document.documentElement.lang = lang;
  }

  function setLang(next) {
    if (!DICTS[next]) return;
    lang = next;
    try { localStorage.setItem('epu.lang', next); } catch (e) { /* игнорируем */ }
    apply();
    document.dispatchEvent(new CustomEvent('langchange', { detail: { lang } }));
  }

